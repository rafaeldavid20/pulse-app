import { act, cleanup, fireEvent, render, screen } from '@testing-library/react';
import { Suspense } from 'react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import SavedViewPage from './page';
import { fixtureContext } from '@/lib/pql/fixtures';
import { useAppStore } from '@/stores/appStore';
import { useIssueStore } from '@/stores/issueStore';
import { useSavedViewStore } from '@/stores/savedViewStore';
import type { Issue, SavedView, Workspace } from '@/types';

const action = vi.fn(), push = vi.fn();
vi.mock('next/navigation', () => ({ useRouter: () => ({ push }) }));
vi.mock('@/hooks/usePqlContext', () => ({ usePqlContext: () => fixtureContext }));
vi.mock('@/lib/saved-views', () => ({ viewAction: (...args: unknown[]) => action(...args) }));
vi.mock('@/components/layout/Header', () => ({ Header: ({ title }: { title: string }) => <header>{title}</header> }));
vi.mock('@/components/issues/IssueList', () => ({ IssueList: ({ issues }: { issues: Issue[] }) => <div>{issues.map(i => <span key={i.id}>{i.identifier}</span>)}</div> }));
vi.mock('@/components/issues/IssueBoard', () => ({ IssueBoard: ({ groupByOverride }: { groupByOverride: string }) => <div>Board: {groupByOverride}</div> }));
const view: SavedView = { id: 'view-a', workspaceId: 'fixture', ownerId: 'user-a', name: 'Mi vista', query: 'assignee = me()', queryVersion: 1, display: 'list', shared: false, createdAt: '2024-01-01', updatedAt: '2024-01-01' };
beforeEach(() => {
  action.mockReset(); push.mockReset();
  useAppStore.setState({ activeWorkspace: { id: 'fixture' } as Workspace, workspaceUserId: 'user-a', members: [], teams: [], workspaceCatalogReady: true, workspaceCatalogError: null });
  useSavedViewStore.getState().setViews([view]);
  useIssueStore.getState().setIssues([{ id: 'a', workspaceId: 'fixture', teamId: 'team-a', identifier: 'TES-1', assigneeId: 'user-a', status: 'todo', priority: 2, title: 'A', createdAt: '2024-01-01' }, { id: 'b', workspaceId: 'other', identifier: 'NO-1', assigneeId: 'user-a', status: 'todo', priority: 2, title: 'B', createdAt: '2024-01-01' }] as Issue[]);
});
it('restores supported board grouping and rejects incompatible legacy combinations', async () => {
  useSavedViewStore.getState().setViews([{ ...view, display: 'board', grouping: 'epic' }]);
  await act(async () => { render(<Suspense fallback="Cargando"><SavedViewPage params={Promise.resolve({ viewId: 'view-a' })} /></Suspense>); });
  expect(screen.getByText('Board: epic')).toBeTruthy();
  expect((screen.getByLabelText('Agrupar') as HTMLSelectElement).value).toBe('epic');
  cleanup();
  useSavedViewStore.getState().setViews([{ ...view, display: 'board', grouping: 'priority' }]);
  await act(async () => { render(<Suspense fallback="Cargando"><SavedViewPage params={Promise.resolve({ viewId: 'view-a' })} /></Suspense>); });
  expect(screen.getByRole('alert').textContent).toContain('agrupación incompatible');
  expect(screen.queryByText(/Board:/)).toBeNull();
  fireEvent.change(screen.getByLabelText('Agrupar'), { target: { value: 'status' } });
  expect(screen.getByText('Board: status')).toBeTruthy();
});
it('sends the loaded version and preserves the draft on a conflict', async () => {
  action.mockRejectedValue(new Error('La vista cambió desde que la abriste.'));
  await act(async () => { render(<Suspense fallback="Cargando"><SavedViewPage params={Promise.resolve({ viewId: 'view-a' })} /></Suspense>); });
  fireEvent.change(screen.getByLabelText('Nombre'), { target: { value: 'Mi borrador' } });
  act(() => useSavedViewStore.getState().setViews([{ ...view, name: 'Cambio ajeno', updatedAt: '2024-02-01' }]));
  fireEvent.click(screen.getByRole('button', { name: 'Guardar' }));
  expect((await screen.findByRole('alert')).textContent).toContain('cambió');
  expect(action.mock.calls[0][1].expectedUpdatedAt).toBe('2024-01-01');
  expect((screen.getByLabelText('Nombre') as HTMLInputElement).value).toBe('Mi borrador');
  fireEvent.click(screen.getByRole('button', { name: 'Descartar' }));
  expect((screen.getByLabelText('Nombre') as HTMLInputElement).value).toBe('Cambio ajeno');
});
it('changes the active ORDER BY, saves it, and restores it after reopening', async () => {
  const original = { ...view, query: 'assignee = me() ORDER BY updated DESC, priority ASC', ordering: [{ field: 'created', direction: 'desc' as const }] };
  useSavedViewStore.getState().setViews([original]);
  action.mockImplementation(async (_action, data) => ({ ...original, ...data, updatedAt: '2024-02-01' }));
  await act(async () => { render(<Suspense fallback="Cargando"><SavedViewPage params={Promise.resolve({ viewId: 'view-a' })} /></Suspense>); });
  const order = screen.getByLabelText('Orden') as HTMLSelectElement;
  expect(order.value).toBe('custom');
  fireEvent.change(order, { target: { value: 'priority:asc' } });
  expect((screen.getByLabelText('Consulta PQL') as HTMLTextAreaElement).value).toMatch(/ORDER BY priority(?: ASC)?/i);
  expect((screen.getByLabelText('Consulta PQL') as HTMLTextAreaElement).value).not.toMatch(/updated DESC/i);
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Guardar' })); });
  const sent = action.mock.calls[0][1];
  expect(sent.ordering).toEqual([]);
  expect(sent.query).toMatch(/ORDER BY priority(?: ASC)?/i);
  cleanup();
  useSavedViewStore.getState().setViews([{ ...original, ...sent, updatedAt: '2024-02-01' }]);
  await act(async () => { render(<Suspense fallback="Cargando"><SavedViewPage params={Promise.resolve({ viewId: 'view-a' })} /></Suspense>); });
  expect((screen.getByLabelText('Orden') as HTMLSelectElement).value).toBe('priority:asc');
  fireEvent.change(screen.getByLabelText('Orden'), { target: { value: '' } });
  expect((screen.getByLabelText('Consulta PQL') as HTMLTextAreaElement).value).not.toMatch(/ORDER BY/i);
});
it('changes the fallback order when the query has no ORDER BY', async () => {
  useSavedViewStore.getState().setViews([{ ...view, ordering: [{ field: 'updated', direction: 'desc' }] }]);
  await act(async () => { render(<Suspense fallback="Cargando"><SavedViewPage params={Promise.resolve({ viewId: 'view-a' })} /></Suspense>); });
  expect((screen.getByLabelText('Orden') as HTMLSelectElement).value).toBe('updated:desc');
  fireEvent.change(screen.getByLabelText('Orden'), { target: { value: 'created:desc' } });
  action.mockImplementation(async (_action, data) => ({ ...view, ...data, updatedAt: '2024-02-01' }));
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Guardar' })); });
  expect(action.mock.calls[0][1].ordering).toEqual([{ field: 'created', direction: 'desc' }]);
  expect(action.mock.calls[0][1].query).toBe(view.query);
});
afterEach(cleanup);
it('isolates the workspace and preserves an invalid draft without showing results', async () => {
  await act(async () => { render(<Suspense fallback="Cargando"><SavedViewPage params={Promise.resolve({ viewId: 'view-a' })} /></Suspense>); });
  expect(await screen.findByText('TES-1')).toBeTruthy(); expect(screen.queryByText('NO-1')).toBeNull();
  fireEvent.change(screen.getByLabelText('Consulta PQL'), { target: { value: 'status =' } });
  expect(screen.getByRole('alert').textContent).toContain('Se esperaba un valor');
  expect(screen.queryByText('TES-1')).toBeNull();
  fireEvent.click(screen.getByRole('button', { name: 'Descartar' }));
  expect(screen.getByText('TES-1')).toBeTruthy();
  act(() => useSavedViewStore.getState().setViews([]));
  expect(screen.getByText(/no está disponible/)).toBeTruthy();
});
it('keeps edits on a failed save and offers a private copy to a shared-view reader', async () => {
  action.mockRejectedValue(new Error('Sin permiso'));
  await act(async () => { render(<Suspense fallback="Cargando"><SavedViewPage params={Promise.resolve({ viewId: 'view-a' })} /></Suspense>); });
  const name = screen.getByLabelText('Nombre') as HTMLInputElement;
  fireEvent.change(name, { target: { value: 'Editada' } });
  fireEvent.click(screen.getByRole('button', { name: 'Guardar' }));
  expect((await screen.findByRole('alert')).textContent).toContain('Sin permiso');
  expect(name.value).toBe('Editada');
  cleanup();
  useAppStore.setState({ workspaceUserId: 'reader' });
  useSavedViewStore.getState().setViews([{ ...view, shared: true }]);
  await act(async () => { render(<Suspense fallback="Cargando"><SavedViewPage params={Promise.resolve({ viewId: 'view-a' })} /></Suspense>); });
  expect(screen.queryByRole('button', { name: 'Guardar' })).toBeNull();
  expect(screen.getByRole('button', { name: 'Guardar copia' })).toBeTruthy();
});
